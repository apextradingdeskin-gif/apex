import { test, expect } from '@playwright/test';

const headers = { 'X-Apex-Client': 'web' };
const password = 'Launch-browser-password-2026!';
async function ownerLogin(page) {
  await page.goto('/admin', { waitUntil: 'domcontentloaded' });
  await page.getByLabel('Administrator email').fill('browser-owner@example.test');
  await page.getByLabel('Password', { exact: true }).fill('Browser-test-owner-2026!');
  await page.getByRole('button', { name: 'Sign in securely' }).click();
  await expect(page.locator('.admin-sidebar')).toBeVisible();
}

test('owner manages payout methods and members see only the selected method questions', async ({ page, browser }) => {
  const errors = []; page.on('pageerror', (error) => errors.push(error.message));
  await ownerLogin(page);
  await page.locator('.admin-sidebar nav').getByRole('button', { name: /Payout requests/ }).click();
  await page.getByRole('button', { name: 'Payout methods', exact: true }).click();
  await page.getByRole('button', { name: 'Add payout method', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Add payout method' });
  await editor.getByLabel('Method name', { exact: true }).fill('Wise Payout');
  await editor.getByLabel('Short description').fill('Receive cashback using your Wise account.');
  const first = editor.locator('.method-question-editor').nth(0);
  await first.getByLabel('Question label', { exact: true }).fill('Wise account email');
  await first.getByRole('combobox', { name: 'Answer type', exact: true }).selectOption('email');
  await first.getByRole('combobox', { name: 'Answer purpose', exact: true }).selectOption('destination');
  await editor.getByRole('button', { name: 'Add question', exact: true }).click();
  const second = editor.locator('.method-question-editor').nth(1);
  await second.getByLabel('Question label', { exact: true }).fill('Payment region');
  await second.getByRole('combobox', { name: 'Answer type', exact: true }).selectOption('select');
  await second.getByLabel('Options (comma separated)', { exact: true }).fill('United States, India');
  await editor.getByRole('button', { name: 'Save payout method' }).click();
  await expect(editor).toHaveCount(0);
  const method = page.locator('.method-management-list > article').filter({ hasText: 'Wise Payout' });
  await expect(method).toContainText('2 questions');
  await page.screenshot({ path: 'test-results/payout-method-management.png', fullPage: true });

  const memberContext = await browser.newContext({ baseURL: new URL(page.url()).origin, reducedMotion: 'reduce', viewport: { width: 1280, height: 1000 } });
  const memberPage = await memberContext.newPage();
  const registration = await memberContext.request.post('/api/auth/register', { headers, data: { name: 'Payout Forms Member', email: 'payout-forms@example.test', password } });
  expect(registration.status()).toBe(201);
  await memberContext.request.post('/api/purchases', { headers, data: { firmId: 'shark-funded', orderId: 'CUSTOM-METHOD-ORDER', amount: 1000, purchaseDate: new Date().toISOString() } });
  const adminState = await page.request.get('/api/admin/state').then((response) => response.json());
  const order = adminState.allPurchases.find((item) => item.orderId === 'CUSTOM-METHOD-ORDER');
  await page.request.patch('/api/admin/purchases/' + order.id, { headers, data: { status: 'approved', adminNote: 'Verified custom form fixture' } });
  await memberPage.goto('/#dashboard', { waitUntil: 'domcontentloaded' });
  await memberPage.locator('.dashboard-sidebar nav').getByRole('button', { name: 'Cashback', exact: true }).click();
  await memberPage.getByRole('button', { name: 'Request payout', exact: true }).click();
  const payout = memberPage.getByRole('dialog', { name: 'Request a cashback payout' });
  await payout.getByRole('combobox', { name: 'Payout method', exact: true }).selectOption('wise-payout');
  await expect(payout.getByLabel('PayPal email address')).toHaveCount(0);
  await expect(payout.getByLabel('UPI ID')).toHaveCount(0);
  await payout.getByLabel('Payout amount (USD)').fill('50');
  await payout.getByLabel('Wise account email', { exact: true }).fill('wise-private-recipient@example.test');
  await payout.getByRole('combobox', { name: 'Payment region', exact: true }).selectOption('India');
  await payout.locator('.form-check').click();
  await memberPage.screenshot({ path: 'test-results/custom-payout-form.png', fullPage: false });
  await payout.getByRole('button', { name: 'Submit payout request' }).click();
  await expect(payout).toHaveCount(0);
  await expect(memberPage.locator('.payout-history tbody tr')).toContainText('Wise Payout');
  const publicState = await memberContext.request.get('/api/bootstrap').then((response) => response.json());
  expect(JSON.stringify(publicState)).not.toContain('wise-private-recipient@example.test');

  await method.getByRole('button', { name: 'Retire', exact: true }).click();
  await expect(method).toContainText('retired');
  await memberPage.reload({ waitUntil: 'domcontentloaded' });
  await memberPage.locator('.dashboard-sidebar nav').getByRole('button', { name: 'Cashback', exact: true }).click();
  await memberPage.getByRole('button', { name: 'Request payout', exact: true }).click();
  await expect(memberPage.getByRole('dialog').getByRole('option', { name: 'Wise Payout' })).toHaveCount(0);
  await memberPage.getByRole('button', { name: 'Close dialog' }).click();

  await page.locator('.payout-desk-tabs').getByRole('button', { name: 'Payout requests', exact: true }).click();
  const row = page.locator('.admin-payout-operations tbody tr').filter({ hasText: 'Payout Forms Member' });
  await row.getByRole('button', { name: 'Review payout' }).click();
  const review = page.getByRole('dialog', { name: 'Review payout request' });
  await expect(review.locator('.payout-private-answers')).toContainText('wise-private-recipient@example.test');
  await expect(review.locator('.payout-private-answers')).toContainText('India');
  await review.getByRole('combobox', { name: 'Next status', exact: true }).selectOption('rejected');
  await review.getByLabel('Member-facing note (reason required)').fill('Test request closed after method verification.');
  await review.getByRole('button', { name: 'Save payout status' }).click();
  await expect(review).toHaveCount(0);
  await page.locator('.payout-desk-tabs').getByRole('button', { name: 'Payout methods', exact: true }).click();
  page.once('dialog', (dialog) => dialog.accept());
  await method.getByRole('button', { name: 'Remove', exact: true }).click();
  await expect(method).toHaveCount(0);
  await memberPage.reload({ waitUntil: 'domcontentloaded' });
  await memberPage.locator('.dashboard-sidebar nav').getByRole('button', { name: 'Cashback', exact: true }).click();
  await expect(memberPage.locator('.payout-history tbody tr')).toContainText('Wise Payout');
  await expect(memberPage.locator('.payout-history tbody tr')).toContainText('rejected');
  await memberContext.close(); expect(errors).toEqual([]);
});

test('admins unsuspend members and the purchase form contains no tracking classification', async ({ page, browser }) => {
  const errors = []; page.on('pageerror', (error) => errors.push(error.message));
  const memberContext = await browser.newContext({ baseURL: 'http://127.0.0.1:5187', reducedMotion: 'reduce' });
  const memberPage = await memberContext.newPage();
  await memberContext.request.post('/api/auth/register', { headers, data: { name: 'Reactivated Member', email: 'reactivated@example.test', password } });
  await ownerLogin(page);
  await page.locator('.admin-sidebar nav').getByRole('button', { name: 'Members', exact: true }).click();
  await page.locator('.admin-global-search input').fill('reactivated@example.test');
  const row = page.locator('.admin-table tbody tr').filter({ hasText: 'Reactivated Member' });
  await row.getByRole('button', { name: 'Suspend', exact: true }).click();
  await expect(row.locator('.admin-status')).toHaveText('suspended');
  await page.locator('.admin-filters').getByRole('button', { name: 'suspended', exact: true }).click();
  await expect(row).toBeVisible();
  await memberPage.goto('/#home', { waitUntil: 'domcontentloaded' });
  await memberPage.locator('.nav-actions').getByRole('button', { name: 'Log in', exact: true }).click();
  const login = memberPage.locator('.auth-form');
  await login.locator('input[type="email"]').fill('reactivated@example.test');
  await login.locator('input[autocomplete="current-password"]').fill(password);
  await login.getByRole('button', { name: 'Log in to APEX' }).click();
  await expect(login.getByRole('alert')).toContainText('suspended');
  await row.getByRole('button', { name: 'Unsuspend', exact: true }).click();
  await page.locator('.admin-filters').getByRole('button', { name: 'all', exact: true }).click();
  await expect(row.locator('.admin-status')).toHaveText('active');
  await login.getByRole('button', { name: 'Log in to APEX' }).click();
  await expect(memberPage.locator('.dashboard-topbar h1')).toContainText('Reactivated');
  await memberPage.locator('.dashboard-top-actions').getByRole('button', { name: 'Add purchase', exact: true }).click();
  const purchase = memberPage.getByRole('dialog', { name: 'Add a purchase' });
  await expect(purchase).toBeVisible();
  expect(await purchase.innerText()).not.toMatch(/tracked|untracked|webhook|attribution/i);
  await purchase.getByRole('combobox', { name: 'Prop firm', exact: true }).selectOption('shark-funded');
  await purchase.getByLabel('Order / invoice ID').fill('REACTIVATED-PURCHASE');
  await purchase.getByLabel('Net purchase amount (USD)').fill('200');
  await memberPage.screenshot({ path: 'test-results/simplified-purchase-form.png', fullPage: false });
  await purchase.locator('.form-check').click();
  await purchase.getByRole('button', { name: 'Add purchase', exact: true }).click();
  await expect(memberPage.getByRole('heading', { name: 'Purchase added', exact: true })).toBeVisible();
  await memberContext.close(); expect(errors).toEqual([]);
});