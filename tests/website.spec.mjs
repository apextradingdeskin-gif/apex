  await form.locator('input[autocomplete="new-password"]').nth(0).fill('Member-test-password-2026!');
  await form.locator('input[autocomplete="new-password"]').nth(1).fill('Member-test-password-2026!');
  await form.locator('.form-check').click();
  await form.getByRole('button', { name: 'Create free account' }).click();
  await expect(page.locator('.dashboard-topbar h1')).toContainText('Browser');
  await expect(page.locator('a[href="/admin"], a[href="#admin"]')).toHaveCount(0);
