  await expect(page.getByText('Preview tools')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Approve', exact: true })).toHaveCount(0);
  await page.evaluate(() => {
    localStorage.setItem('apex_admin_profile_v1', JSON.stringify({ email: 'browser-member@example.test', role: 'admin' }));
    sessionStorage.setItem('apex_admin_session_v1', 'browser-member@example.test');
  });
  await page.goto('/admin', { waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('heading', { name: 'This page is restricted' })).toBeVisible();
